import {
  renderAnatomyMarkdown,
  renderPropertiesTable,
  renderLayoutTable,
  renderVariantSpecs,
  renderVariantRows
} from "./figma-node-spec-extractor.mjs";

function makeHeader(slug) {
  return `<!-- 
  ⚠️ AUTO-GENERATED: DO NOT EDIT
  Source: docs/_spec/components/${slug}.yml
  Generated by: ds-spec-to-markdown
-->\n`;
}

/**
 * Validates and safely injects content between HTML string boundaries.
 */
function processZone(markdown, zoneName, contentToInject, slug) {
  const startTag = `<!-- AUTO-GENERATED-${zoneName}:START -->`;
  const endTag = `<!-- AUTO-GENERATED-${zoneName}:END -->`;

  const startIdx = markdown.indexOf(startTag);
  const endIdx = markdown.indexOf(endTag);

  if (startIdx === -1 && endIdx === -1) {
    console.warn(`[WARNING] Zone tag missing for ${zoneName}. Appending safely at the end of the document.`);
    // Append the standalone block
    return markdown.replace(/\n*$/, "") + `\n\n${startTag}\n${makeHeader(slug)}${contentToInject}\n${endTag}\n`;
  }

  if (startIdx === -1 || endIdx === -1) {
    throw new Error(`Corrupted boundaries for ${zoneName}: Missing ${startIdx === -1 ? 'START' : 'END'} tag.`);
  }

  if (startIdx > endIdx) {
    throw new Error(`Corrupted boundaries for ${zoneName}: END tag appears before START tag.`);
  }

  const startTagOccurrences = markdown.split(startTag).length - 1;
  const endTagOccurrences = markdown.split(endTag).length - 1;
  if (startTagOccurrences > 1 || endTagOccurrences > 1) {
    throw new Error(`Ambiguity for ${zoneName}: Multiple identical tags found.`);
  }

  const before = markdown.slice(0, startIdx + startTag.length);
  const after = markdown.slice(endIdx);
  const newContent = `\n${makeHeader(slug)}${contentToInject}\n`;
  
  return before + newContent + after;
}

/**
 * Main Injector
 * 
 * @param {string} markdown - The raw markdown file text
 * @param {object} spec - The structured component specification object
 * @param {string} slug - The component slug
 * @returns {string} The mutated markdown with safely injected zones
 */
export function injectSpecZones(markdown, spec, slug) {
  if (typeof markdown !== "string") {
    throw new Error("Markdown content must be a string.");
  }
  if (!spec || typeof spec !== "object") {
    throw new Error("YAML spec must be a valid object.");
  }

  let result = markdown;

  // 1. Anatomy Zone
  const anatomyContent = renderAnatomyMarkdown(spec.anatomy);
  result = processZone(result, "ANATOMY", anatomyContent, slug);

  // 2. Properties Zone
  const rawPropsRows = renderPropertiesTable(spec.properties);
  const propsTable = `| Name | Type | Default | Required | Description | Narrative Notes |\n| --- | --- | --- | --- | --- | --- |\n${rawPropsRows}`;
  result = processZone(result, "PROPERTIES", propsTable, slug);

  // 3. Visuals Zone (Diffs and Layout)
  const diffs = renderVariantSpecs(spec.variants) || "- `TBD`\n";
  const rawLayoutRows = renderLayoutTable(spec.layout);
  const layoutTable = `| Node | Direction | Alignment | H Sizing | V Sizing | Item Spacing | Padding (T/R/B/L) |\n| --- | --- | --- | --- | --- | --- | --- |\n${rawLayoutRows}`;
  const visualsContent = `### Per-variant attributes\n\n${diffs}\n### Layout and spacing\n\n${layoutTable}`;
  result = processZone(result, "VISUALS", visualsContent, slug);

  // 4. Variants Matrix Zone
  const rawVarRows = renderVariantRows(spec.variants);
  const matrixContent = `| Variant | Token | Fallback | Notes |\n| --- | --- | --- | --- |\n${rawVarRows}\n`;
  result = processZone(result, "VARIANTS", matrixContent, slug);

  return result;
}
